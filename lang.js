   function normalize(value) {
      return value.replace(/\s+/g, " ").trim();
   }

   function currentLanguage() {
      const saved = getStoredValue(LANG_STORAGE_KEY) || "en";
      return supportedLanguages.includes(saved) ? saved : "en";
   }

   function getTranslatableElements() {
      return Array.from(document.body.querySelectorAll("a, button span, h1, h2, h3, p, small, figcaption span, figcaption strong, article span, .funnel-card span, .partner-strip span"));
   }

   function rememberSource(element) {
      const text = normalize(element.textContent || "");
      if (!text || element.closest(".language-switcher")) return null;
      if (!element.dataset.i18nSource && (translations.ru[text] || translations.kz[text] || text === "EN" || text === "RU" || text === "KZ")) {
         element.dataset.i18nSource = text;
      }
      return element.dataset.i18nSource || null;
   }

   function applyLanguage(lang) {
      document.documentElement.lang = lang === "kz" ? "kk" : lang;
      document.body.dataset.lang = lang;
      getTranslatableElements().forEach((element) => {
         const source = rememberSource(element);
         if (!source) return;
         const nextText = lang === "en" ? source : translations[lang][source] || source;
         if (element.textContent !== nextText) {
            element.textContent = nextText;
         }
      });
      document.querySelectorAll(".language-option").forEach((button) => {
         const isActive = button.dataset.lang === lang;
         button.classList.toggle("is-active", isActive);
         button.setAttribute("aria-pressed", String(isActive));
      });
      setStoredValue(LANG_STORAGE_KEY, lang);
   }

   function buildSwitcher() {
      const headerActions = document.querySelector(".header-actions");
      if (!headerActions || headerActions.querySelector(".language-switcher")) return;

      const switcher = document.createElement("div");
      switcher.className = "language-switcher";
      switcher.setAttribute("aria-label", "Language switcher");

      supportedLanguages.forEach((lang) => {
         const button = document.createElement("button");
         button.type = "button";
         button.className = "language-option";
         button.dataset.lang = lang;
         button.textContent = languageLabels[lang];
         button.setAttribute("aria-label", `Switch language to ${languageLabels[lang]}`);
         button.addEventListener("click", () => applyLanguage(lang));
         switcher.appendChild(button);
      });

      headerActions.prepend(switcher);
   }

   document.addEventListener("DOMContentLoaded", () => {
      buildSwitcher();
      applyLanguage(currentLanguage());

      const themeToggle = document.querySelector(".theme-toggle");
      if (themeToggle) {
         const observer = new MutationObserver(() => applyLanguage(currentLanguage()));
         observer.observe(themeToggle, { childList: true, subtree: true, characterData: true });
      }
   });
